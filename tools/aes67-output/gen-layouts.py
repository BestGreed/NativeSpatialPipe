"""Generate tools/aes67-output/aes67_layouts.h from contracts/output-layouts.json.

The SDP generator does not parse JSON at runtime: the single-source contract is
consumed here at build time so the C code stays dependency-free. Run from the
repo root:

    python tools/aes67-output/gen-layouts.py

The generated header is committed so a plain gcc aes67_*.c build works even
without Python; Build.ps1 regenerates it to prove it still matches the contract.
"""
import json
import pathlib
import sys

# Informative SMPTE ST 2110-30 channel-order tokens. AES67 itself does not
# normatively define a channel-order token; these are a pragmatic approximation
# for receivers that understand the ST 2110 convention (see docs/aes67-output.md).
SMPTE_ORDER = {
    # 4.1.2 is an NSP extension: SMPTE ST 2110-30 defines no such token, so this
    # follows its (bed,height) spelling and is informative only. Receivers that
    # need the exact order must use a=comment:channel-labels in the same SDP.
    "4.1.2": "SMPTE2110.(41,2)",
    "5.1.2": "SMPTE2110.(51,2)",
    "5.1.4": "SMPTE2110.(51,4)",
    "7.1.2": "SMPTE2110.(71,2)",
    "7.1.4": "SMPTE2110.(71,4)",
    "7.1.6": "SMPTE2110.(71,6)",
    "9.1.4": "SMPTE2110.(91,4)",
    "9.1.6": "SMPTE2110.(91,6)",
}


def main() -> int:
    root = pathlib.Path(__file__).resolve().parents[2]
    contract_path = root / "contracts" / "output-layouts.json"
    out_path = pathlib.Path(__file__).resolve().parent / "aes67_layouts.h"
    contract = json.loads(contract_path.read_text(encoding="utf-8"))
    lines = [
        "/* Generated by tools/aes67-output/gen-layouts.py from contracts/output-layouts.json.",
        " * Do not edit by hand. Regenerate: python tools/aes67-output/gen-layouts.py",
        " * SPDX-License-Identifier: Apache-2.0",
        " */",
        "#ifndef NSP_AES67_LAYOUTS_H",
        "#define NSP_AES67_LAYOUTS_H",
        "",
        "#include <stdint.h>",
        "",
        "#define NSP_AES67_LAYOUT_MAX_CHANNELS 16u",
        "",
        "typedef struct nsp_aes67_layout {",
        "    const char *id;",
        "    uint16_t channels;",
        "    uint32_t code;",
        "    const char *smpte_order;",
        "    const char *labels[NSP_AES67_LAYOUT_MAX_CHANNELS];",
        "} nsp_aes67_layout;",
        "",
        "static const nsp_aes67_layout nsp_aes67_layouts[] = {",
    ]
    for layout in contract["layouts"]:
        labels = layout["channels"]
        if len(labels) > 16:
            raise SystemExit("layout %s has %d > 16 channels" % (layout["id"], len(labels)))
        label_list = ", ".join('"%s"' % label for label in labels)
        label_list += ", 0" * (16 - len(labels))
        lines.append(
            '    {"%s", %d, %du, "%s", {%s}},'
            % (layout["id"], len(labels), layout["code"], SMPTE_ORDER.get(layout["id"], "SMPTE2110.(CUSTOM)"), label_list)
        )
    lines += [
        "};",
        "",
        "static const uint16_t nsp_aes67_layout_count =",
        "    (uint16_t)(sizeof(nsp_aes67_layouts) / sizeof(nsp_aes67_layouts[0]));",
        "",
        'static const char *nsp_aes67_default_layout = "' + str(contract.get("default", "7.1.4")) + '";',
        "",
        "#endif /* NSP_AES67_LAYOUTS_H */",
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote %s (%d layouts)" % (out_path, len(contract["layouts"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())

