"""Generate the C/C++ PCM profile table from the shipped capture-profile table.

Usage:
    python tools/capture-profile/gen_pcm_header.py \
        --table modules/native-capture/profiles/capture-profiles.json \
        --out modules/pcm-capture/profile.generated.h

Only the table decides what the PCM path may use: a layout contributes a usable
row only at level `anchor` with all anchors and the 32-byte entry prologue
present. `address` (no prologue) and `unavailable` rows stay in the header as
disabled entries so the C side can report the identity it saw.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import layout

PROLOGUE_BYTES = 32
LEVELS = {"unavailable": 0, "address": 1, "anchor": 2}
LEVEL_NAMES = {0: "unavailable", 1: "address", 2: "anchor"}


def load_table(path):
    with open(path, encoding="utf-8") as fh:
        table = json.load(fh)
    if not isinstance(table, dict) or not isinstance(table.get("layouts"), dict) \
            or not isinstance(table.get("members"), dict):
        raise layout.LayoutError("table needs layouts and members")
    return table


def anchor_row(layout_id, pcm):
    """Return (level, getInputRva, inputVtableRva, baseOffset, prologue)."""
    level = LEVELS.get(pcm.get("level"), 0)
    prologue_hex = pcm.get("prologue") or ""
    get_input = pcm.get("getInputRva")
    vtable = pcm.get("inputVtableRva")
    base = pcm.get("baseOffset")
    if level != LEVELS["anchor"]:
        return level, 0, 0, 0, bytes(PROLOGUE_BYTES)
    if not isinstance(get_input, int) or get_input <= 0:
        raise layout.LayoutError("%s: anchor without getInputRva" % layout_id)
    if not isinstance(vtable, int) or vtable <= 0:
        raise layout.LayoutError("%s: anchor without inputVtableRva" % layout_id)
    if not isinstance(base, int) or not (-0x800 <= base < 0):
        raise layout.LayoutError("%s: anchor with invalid baseOffset" % layout_id)
    if len(prologue_hex) != PROLOGUE_BYTES * 2:
        raise layout.LayoutError(
            "%s: anchor needs %d prologue bytes, have %d hex chars"
            % (layout_id, PROLOGUE_BYTES, len(prologue_hex)))
    try:
        prologue = bytes.fromhex(prologue_hex)
    except ValueError:
        raise layout.LayoutError("%s: prologue is not hex" % layout_id)
    return level, get_input, vtable, base, prologue


def rows(table):
    out = []
    for key in sorted(table["members"]):
        layout_id = table["members"][key]
        layout_entry = table["layouts"].get(layout_id)
        if not isinstance(layout_entry, dict):
            raise layout.LayoutError("%s points at unknown layout %s" % (key, layout_id))
        pcm = layout_entry.get("pcm")
        if not isinstance(pcm, dict):
            level, get_input, vtable, base, prologue = 0, 0, 0, 0, bytes(PROLOGUE_BYTES)
        else:
            level, get_input, vtable, base, prologue = anchor_row(layout_id, pcm)
        out.append({"key": key, "layout": layout_id, "level": level,
                    "getInputRva": get_input, "inputVtableRva": vtable,
                    "baseOffset": base, "prologue": prologue})
    return out


def render(table_path, entries):
    name = os.path.basename(table_path)
    lines = [
        "// Generated by tools/capture-profile/gen_pcm_header.py from %s." % name,
        "// Do not edit; rebuild the PCM module to regenerate.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define NSP_PCM_PROFILE_COUNT %d" % len(entries),
        "",
        "enum { NSP_PCM_UNAVAILABLE = 0, NSP_PCM_ADDRESS = 1, NSP_PCM_ANCHOR = 2 };",
        "",
        "typedef struct {",
        "    const char *symbolKey;",
        "    const char *layout;",
        "    int level;",
        "    uint32_t getInputRva;",
        "    uint32_t inputVtableRva;",
        "    int32_t baseOffset;",
        "    uint8_t prologue[%d];" % PROLOGUE_BYTES,
        "} NspPcmProfile;",
        "",
        "static const NspPcmProfile NSP_PCM_PROFILES[NSP_PCM_PROFILE_COUNT] = {",
    ]
    for entry in entries:
        prologue = ", ".join("0x%02x" % byte for byte in entry["prologue"])
        lines.append('    {"%s", "%s", %d, %du, %du, %d, {%s}}, /* %s */' % (
            entry["key"], entry["layout"], entry["level"], entry["getInputRva"],
            entry["inputVtableRva"], entry["baseOffset"], prologue,
            LEVEL_NAMES[entry["level"]]))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", default="modules/native-capture/profiles/capture-profiles.json")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    table = load_table(args.table)
    entries = rows(table)
    if not entries:
        print("FAIL %s: no members" % args.table)
        return 1
    text = render(args.table, entries)
    directory = os.path.dirname(args.out)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    usable = sum(1 for entry in entries if entry["level"] == LEVELS["anchor"])
    print("wrote %s (%d members, %d anchor, %d disabled)" % (
        args.out, len(entries), usable, len(entries) - usable))
    return 0


if __name__ == "__main__":
    sys.exit(main())
