"""Generate immutable preset tables from the shared output-layout contract."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
catalog=json.loads((ROOT/'contracts/output-layouts.json').read_text(encoding='utf-8'))
layouts=catalog['layouts']
def write(path,text): (ROOT/path).write_text(text,encoding='utf-8')
def quoted(items): return ','.join(json.dumps(item) for item in items)
zig='// Generated by tools/Generate-OutputLayouts.py; edit contracts/output-layouts.json.\nconst std=@import("std");\npub const Preset=struct{id:[]const u8,code:u32,labels:[]const []const u8};\npub const presets=[_]Preset{\n'
for row in layouts:zig+='.{.id="'+row['id']+'",.code='+str(row['code'])+',.labels=&.{'+quoted(row['channels'])+'}},\n'
zig+='};\npub fn get(id:[]const u8) ?Preset {for(presets) |p| if(std.mem.eql(u8,id,p.id))return p;return null;}\n'
write('tools/zig-scheduler/layout_presets.zig',zig)
rust='// Generated by tools/Generate-OutputLayouts.py.\nuse aom_roar::Layout;\n#[derive(Clone,Copy)]\npub struct Preset{pub code:u32,pub id:&\'static str,pub labels:&\'static [&\'static str],pub roar:Layout}\npub fn get(code:u32)->Result<Preset,String>{match code{\n'
for row in layouts:rust+=f'{row["code"]}=>Ok(Preset{{code,id:"{row["id"]}",labels:&[{quoted(row["channels"])}],roar:Layout::{row["roar"]}}}),\n'
rust+='_=>Err("Unsupported output layout".into())}}\n'
write('tools/roar-bridge/src/layouts.rs',rust)
canonical=['L','R','C','LFE','Lrs','Rrs','Ls','Rs','Lw','Rw','Ltf','Rtf','Ltm','Rtm','Ltr','Rtr']
cpp='// Generated by tools/Generate-OutputLayouts.py.\n#pragma once\n#include <vector>\n#include <stdexcept>\ninline std::vector<unsigned> NspLayoutIndices(unsigned code){switch(code){\n'
for row in layouts:cpp+=f'case {row["code"]}:return {{'+','.join(str(canonical.index(c)) for c in row['channels'])+'};\n'
cpp+='default:throw std::invalid_argument("Unsupported NSP output layout");}}\n'
write('modules/audio-backends/src/layout_presets.h',cpp)
write('tools/visualization-frontend/layout-presets.js','// Generated by tools/Generate-OutputLayouts.py.\nexport const outputLayouts='+json.dumps(layouts,ensure_ascii=False,separators=(',',':'))+';\n')
aliases=dict(zip(canonical,['FL','FR','C','LFE','BL','BR','SL','SR','FWL','FWR','TFL','TFR','TML','TMR','TBL','TBR']))
rows={row['id']:[aliases[c] for c in row['channels']] for row in layouts}
write('tools/telemetry/layout_presets.py','# Generated by tools/Generate-OutputLayouts.py.\nLAYOUTS='+repr(rows)+'\n')
print('Generated seven output layout tables')
