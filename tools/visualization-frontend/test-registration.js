import assert from 'node:assert/strict';
import {weightedProcrustes,robustRegister} from './navigation-core.js';
const norm=a=>Math.hypot(...a),sub=(a,b)=>a.map((x,i)=>x-b[i]);
const angle=.27,c=Math.cos(angle),s=Math.sin(angle),translate=[.24,-.11,.19];
const rotate=p=>[c*p[0]+s*p[2],p[1],-s*p[0]+c*p[2]];
const source=Array.from({length:30},(_,i)=>[Math.sin(i*2.399)*3,(i%7-3)*.47,Math.cos(i*1.13)*2.4]);
const pairs=source.map((a,i)=>({a,b:i<17?rotate(a).map((x,k)=>x+translate[k]):[Math.sin(i*3.1)*5,Math.cos(i*1.7)*3,Math.sin(i*4.2)*6],prior:i<17?1:.3}));
const fit=robustRegister(pairs,{metric:true,iterations:128});
assert(fit&&!fit.degenerate&&fit.inlierRatio>.53);
assert(norm(sub(fit.t,translate))<.02);
assert(norm(sub(fit.r,[c,0,s,0,1,0,-s,0,c]))<.02);
const directionPairs=pairs.map((p,i)=>({a:p.a.map(x=>x/norm(p.a)),b:(i<17?rotate(p.a):p.b).map(x=>x/norm(i<17?rotate(p.a):p.b)),prior:p.prior}));
const directionFit=robustRegister(directionPairs,{metric:false,iterations:128});
assert(directionFit);assert.deepEqual(directionFit.t,[0,0,0]);
const exact=weightedProcrustes(pairs.slice(0,17),pairs.slice(0,17).map(()=>1),true);
assert(norm(sub(exact.t,translate))<1e-9);
const degenerate=Array.from({length:12},(_,i)=>({a:[0,0,i],b:[0,0,i+1],prior:1}));
assert(robustRegister(degenerate,{metric:true})===null||robustRegister(degenerate,{metric:true}).degenerate);
console.log('PASS weighted rigid fit, direction-only no translation, 43% independent outliers, geometry degeneration');
