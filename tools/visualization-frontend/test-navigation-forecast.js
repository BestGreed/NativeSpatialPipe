import assert from 'node:assert/strict';
import {NavigationForecast} from './navigation-forecast.js';

const sample=(yaw,flow,valid=true)=>({yaw,pitch:0,result:{valid,confidence:valid?.8:0,coordinateMode:'source',cooperativeFlow:{valid:!!flow},translation:flow,visualFlow:flow}});
const forecast=new NavigationForecast();
forecast.observe(sample(0,[1,0,0]),0);forecast.step(sample(0,[1,0,0]),0);
forecast.observe(sample(.1,[1,0,0]),100);forecast.step(sample(.1,[1,0,0]),100);
const missing=sample(.1,null,false);forecast.observe(missing,200);
const projected=forecast.step(missing,300);
assert.equal(projected.result.prediction.pose,'predicted');
assert.equal(projected.result.prediction.flow,'predicted');
assert(projected.yaw>.1&&projected.yaw<.4,'短时前推应受速率与角度限位');
assert(projected.result.visualFlow[0]>0&&projected.result.visualFlow[0]<1,'无新流向时逐渐衰减');
forecast.observe(sample(0,[-1,0,0]),400);
const conflict=forecast.step(sample(0,[-1,0,0]),400);
assert.equal(conflict.result.prediction.pose,'reconciling');
assert.equal(conflict.result.prediction.flow,'reconciling');
assert(conflict.yaw>0&&conflict.yaw<projected.yaw,'冲突观测不能使姿态瞬间跳回');
assert(conflict.result.visualFlow[0]>-1,'相反流向不能瞬间反转');
let settled=conflict;for(let t=450;t<=1400;t+=50){if(t%100===0)forecast.observe(sample(0,[-1,0,0]),t);settled=forecast.step(sample(0,[-1,0,0]),t);}
assert(Math.abs(settled.yaw)<.015,'前推误差应回归观测姿态');
assert(Math.abs(settled.result.visualFlow[0]+1)<.08,'前推流向应回归后续数据');
forecast.reset();assert.equal(forecast.step(missing,1500).result.prediction.pose,'none','来源切换不得延续前推');
forecast.observe(sample(0,[1,0,0]),2000);forecast.observe(sample(.1,[1,0,0]),2100);
assert.equal(forecast.step(sample(.1,[1,0,0]),2750).result.prediction.pose,'none','超过时限停止前推');
assert.equal(forecast.step(sample(.1,[1,0,0]),2150,{allow:false}).result.prediction.pose,'none','暂停回放不得前推');
console.log('navigation forecast passed');
const sparseSample=yaw=>{const nav=sample(yaw,null);nav.result.navigationCandidate={signals:['sparse-relative-pose']};return nav;};
const sparse=new NavigationForecast();
sparse.observe(sparseSample(0),0);sparse.step(sparseSample(0),0);
sparse.observe(sparseSample(.1),100);
const smoothed=sparse.step(sparseSample(.1),100);
assert(smoothed.yaw>0&&smoothed.yaw<.1,'sparse observation is reconciled smoothly');
sparse.observe(missing,200);
const held=sparse.step(missing,300);
assert.equal(held.result.prediction.pose,'predicted');
assert(held.yaw>smoothed.yaw&&held.yaw<.2,'sparse gaps retain bounded smoothed prediction');
sparse.observe(sparseSample(0),400);
const recovered=sparse.step(sparseSample(0),400);
assert(recovered.yaw>=0&&recovered.yaw<held.yaw,'recovery returns smoothly without overshoot');
assert.equal(sparse.step(missing,1000).result.prediction.pose,'none','holding must expire');
console.log('sparse grid stabilization passed');
const marginal=new NavigationForecast(),low=yaw=>{const n=sample(yaw,null);n.result.confidence=.52;return n;};
marginal.observe(low(0),0);marginal.step(low(0),0);marginal.observe(low(.1),100);
const lowObserved=marginal.step(low(.1),100);marginal.observe(missing,200);
const lowHeld=marginal.step(missing,300);
assert.equal(lowHeld.result.prediction.pose,'predicted','marginal global fits retain bounded prediction');
assert(lowHeld.yaw>lowObserved.yaw&&lowHeld.yaw<.2);
const fading=sparse.step(missing,951);
assert(fading.result.visualAngularVelocity.every(x=>x===0),'angular prediction is zero after deadline');
assert.equal(fading.result.prediction.active,false,'prediction exits explicitly 550ms after last valid sample');
const exit=new NavigationForecast();exit.observe(sample(0,[1,0,0]),0);exit.observe(sample(.1,[1,0,0]),100);exit.observe(missing,200);
const before=exit.step(missing,500),nearEnd=exit.step(missing,640),ended=exit.step(missing,651);
assert(Math.abs(nearEnd.result.visualFlow[0])<Math.abs(before.result.visualFlow[0]),'flow fades before expiry');
assert(Math.hypot(...nearEnd.result.visualAngularVelocity)<Math.hypot(...before.result.visualAngularVelocity),'angular drive fades before expiry');
assert(!ended.result.prediction.active);assert.equal(ended.result.prediction.exitAfterMs,550);
const lockSample=sample(.1,[0,0,0]);lockSample.result.stationaryLock={active:true};
exit.observe(lockSample,700);const lockOutput=exit.step(lockSample,700);
assert(!lockOutput.result.prediction.active,'stationary evidence cancels previously extrapolated motion');
assert.deepEqual(lockOutput.result.visualAngularVelocity,[0,0,0]);assert.deepEqual(lockOutput.result.visualFlow,[0,0,0]);
