"""Generate audiodg capture-hook profile tables from the shared contract.

contracts/audiodg-builds.json is the single source of truth. The hook DLL is
told the target function RVA, the two capture vtables and the expected
16-byte prologue through HookConfig at runtime, so the tables generated here
only select a profile from the full-file audiodg.exe SHA-256 and feed those
fields. Unknown images fail closed in every consumer.

Generated files are committed, mirroring tools/Generate-OutputLayouts.py, so
the native and Python builds never need Python just to compile.

Usage:
  python tools/Generate-AudiodgBuilds.py           # rewrite generated files
  python tools/Generate-AudiodgBuilds.py --check   # verify generated files are current
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / 'contracts/audiodg-builds.json'
OUTPUTS = (
    'tools/backend/audiodg_builds.py',
    'tools/zig-scheduler/audiodg_builds.zig',
    'modules/zig-scheduler/audiodg_builds.zig',
    'tools/endpoint-probe/Audiodg-Builds.h',
    'modules/native-capture/Audiodg-Builds.h',
)
HEX = set('0123456789abcdef')


def fail(message):
    raise SystemExit('Generate-AudiodgBuilds: ' + message)


def parse_digest(value, field, ident):
    if not isinstance(value, str) or len(value) != 64 or any(ch not in HEX for ch in value):
        fail('%s.%s must be 64 lowercase hex characters' % (ident, field))
    return value


def parse_u32(value, field, ident):
    try:
        number = int(value, 0) if isinstance(value, str) else int(value)
    except (TypeError, ValueError):
        fail('%s.%s must be an integer or 0x-prefixed string' % (ident, field))
    if not 0 < number <= 0xffffffff:
        fail('%s.%s must be a positive 32-bit value' % (ident, field))
    return number


def parse_size(value, field, ident):
    number = parse_u32(value, field, ident)
    if number > 0x100000:
        fail('%s.%s is implausibly large' % (ident, field))
    return number


def parse_prologue(value, ident):
    if not isinstance(value, str):
        fail('%s.prologue must be a hex string' % ident)
    raw = bytes.fromhex(value.replace(' ', ''))
    if len(raw) != 16:
        fail('%s.prologue must be exactly 16 bytes' % ident)
    return raw


def load_profiles():
    try:
        catalog = json.loads(CONTRACT.read_text(encoding='utf-8'))
    except FileNotFoundError:
        fail('missing ' + str(CONTRACT))
    except json.JSONDecodeError as exc:
        fail('invalid JSON: %s' % exc)
    rows = catalog.get('profiles')
    if not isinstance(rows, list) or not rows:
        fail('profiles must be a non-empty list')
    profiles = []
    seen_ids, seen_sha = set(), set()
    for row in rows:
        ident = row.get('id')
        if not isinstance(ident, str) or not ident:
            fail('every profile needs a non-empty id')
        if ident in seen_ids:
            fail('duplicate profile id %s' % ident)
        seen_ids.add(ident)
        label = row.get('label')
        if not isinstance(label, str) or not label:
            fail('%s.label must be a non-empty string' % ident)
        sha = parse_digest(row.get('sha256'), 'sha256', ident)
        if sha in seen_sha:
            fail('duplicate sha256 %s' % sha)
        seen_sha.add(sha)
        function_sha = row.get('functionSha256')
        if function_sha is not None:
            function_sha = parse_digest(function_sha, 'functionSha256', ident)
        profiles.append({
            'id': ident,
            'label': label,
            'sha256': sha,
            'targetRva': parse_u32(row.get('targetRva'), 'targetRva', ident),
            'targetSize': parse_size(row.get('targetSize'), 'targetSize', ident),
            'vt1Rva': parse_u32(row.get('vt1Rva'), 'vt1Rva', ident),
            'vt2Rva': parse_u32(row.get('vt2Rva'), 'vt2Rva', ident),
            'prologue': parse_prologue(row.get('prologue'), ident),
            'functionSha256': function_sha,
        })
    if len(profiles) < 2:
        fail('at least two profiles are required for a multi-build table')
    return profiles


def c_bytes(raw):
    return ','.join('0x%02x' % byte for byte in raw)


def render_python(profiles):
    lines = [
        '"""Verified audiodg.exe capture-hook profiles (generated).',
        '',
        'Generated by tools/Generate-AudiodgBuilds.py from contracts/audiodg-builds.json.',
        'Do not edit this file directly: edit the contract and regenerate. An unknown',
        'audiodg.exe SHA-256 must always fail closed with a message that names the actual',
        'digest and every supported build.',
        '"""',
        '',
        'PROFILES = (',
    ]
    for profile in profiles:
        function_sha = profile['functionSha256'] or '0' * 64
        lines.extend([
            '    {',
            "        'id': %s," % json.dumps(profile['id'], ensure_ascii=False),
            "        'label': %s," % json.dumps(profile['label'], ensure_ascii=False),
            "        'sha256': %s," % json.dumps(profile['sha256']),
            "        'sha256Bytes': bytes.fromhex(%s)," % json.dumps(profile['sha256']),
            "        'targetRva': 0x%x," % profile['targetRva'],
            "        'targetSize': %d," % profile['targetSize'],
            "        'vt1Rva': 0x%x," % profile['vt1Rva'],
            "        'vt2Rva': 0x%x," % profile['vt2Rva'],
            "        'prologue': bytes.fromhex(%s)," % json.dumps(profile['prologue'].hex()),
            "        'functionSha256': %s," % json.dumps(function_sha),
            '    },',
        ])
    lines.extend([
        ')',
        '',
        '',
        'def match_build(digest):',
        '    """Return the profile selected by a lowercase hex SHA-256 digest, or None."""',
        '    for profile in PROFILES:',
        "        if profile['sha256'] == digest:",
        '            return profile',
        '    return None',
        '',
        '',
        'def describe_builds():',
        "    return '; '.join('%s (%s)' % (profile['sha256'], profile['label']) for profile in PROFILES) or 'none'",
        '',
        '',
        'def unsupported_build_message(actual):',
        "    return ('Unsupported audiodg build: sha256=%s; supported: %s; '",
        "            'add the verified build to contracts/audiodg-builds.json' % (actual, describe_builds()))",
        '',
        '',
        'def require_build(digest):',
        '    profile = match_build(digest)',
        '    if profile is None:',
        '        raise RuntimeError(unsupported_build_message(digest))',
        '    return profile',
        '',
        '',
        'def apply_profile(config, build):',
        '    """Copy a selected profile into a HookConfig-compatible ctypes structure."""',
        "    config.target_rva = build['targetRva']",
        "    config.target_size = build['targetSize']",
        "    config.vt1_rva = build['vt1Rva']",
        "    config.vt2_rva = build['vt2Rva']",
        "    config.profile_sha256[:] = build['sha256Bytes']",
        "    config.prologue[:] = build['prologue']",
        '    return config',
        '',
    ])
    return '\n'.join(lines)


def render_zig(profiles):
    lines = [
        '// Generated by tools/Generate-AudiodgBuilds.py; edit contracts/audiodg-builds.json.',
        'const std = @import("std");',
        '',
        'pub const Profile = struct {',
        '    id: []const u8,',
        '    label: []const u8,',
        '    sha256: [32]u8,',
        '    target_rva: u32,',
        '    target_size: u32,',
        '    vt1_rva: u32,',
        '    vt2_rva: u32,',
        '    prologue: [16]u8,',
        '    function_sha256: [32]u8,',
        '};',
        '',
        'pub const profiles = [_]Profile{',
    ]
    for profile in profiles:
        function_sha = bytes.fromhex(profile['functionSha256'] or '0' * 64)
        lines.extend([
            '    .{',
            '        .id = %s,' % json.dumps(profile['id']),
            '        .label = %s,' % json.dumps(profile['label'], ensure_ascii=False),
            '        .sha256 = .{ %s },' % c_bytes(bytes.fromhex(profile['sha256'])),
            '        .target_rva = 0x%x,' % profile['targetRva'],
            '        .target_size = %d,' % profile['targetSize'],
            '        .vt1_rva = 0x%x,' % profile['vt1Rva'],
            '        .vt2_rva = 0x%x,' % profile['vt2Rva'],
            '        .prologue = .{ %s },' % c_bytes(profile['prologue']),
            '        .function_sha256 = .{ %s },' % c_bytes(function_sha),
            '    },',
        ])
    lines.extend([
        '};',
        '',
        'pub fn match(digest: *const [32]u8) ?*const Profile {',
        '    for (&profiles) |*profile| if (std.mem.eql(u8, digest, &profile.sha256)) return profile;',
        '    return null;',
        '}',
        '',
        'pub fn describeSupported(buffer: []u8) []const u8 {',
        '    var used: usize = 0;',
        '    for (profiles, 0..) |profile, index| {',
        '        const hex = std.fmt.bytesToHex(profile.sha256, .lower);',
        '        const written = std.fmt.bufPrint(buffer[used..], "{s}{s} ({s})", .{ if (index == 0) "" else "; ", &hex, profile.label }) catch return buffer[0..used];',
        '        used += written.len;',
        '    }',
        '    return buffer[0..used];',
        '}',
        '',
        'pub fn unsupportedMessage(buffer: []u8, digest: *const [32]u8) []const u8 {',
        '    const hex = std.fmt.bytesToHex(digest.*, .lower);',
        '    var supported: [1024]u8 = undefined;',
        '    return std.fmt.bufPrint(buffer, "Unsupported audiodg build: sha256={s}; supported: {s}; add the verified build to contracts/audiodg-builds.json", .{ &hex, describeSupported(&supported) }) catch buffer[0..0];',
        '}',
        '',
    ])
    return '\n'.join(lines)


def render_header(profiles):
    lines = [
        '/* Generated by tools/Generate-AudiodgBuilds.py; edit contracts/audiodg-builds.json. */',
        '#ifndef NSP_AUDIODG_BUILDS_H',
        '#define NSP_AUDIODG_BUILDS_H',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '#include <stdio.h>',
        '#include <string.h>',
        '',
        'typedef struct {',
        '    const char *id;',
        '    const char *label;',
        '    unsigned char sha256[32];',
        '    uint32_t target_rva;',
        '    uint32_t target_size;',
        '    uint32_t vt1_rva;',
        '    uint32_t vt2_rva;',
        '    unsigned char prologue[16];',
        '    unsigned char function_sha256[32];',
        '} NspAudiodgBuild;',
        '',
        'static const NspAudiodgBuild nsp_audiodg_builds[] = {',
    ]
    for profile in profiles:
        function_sha = bytes.fromhex(profile['functionSha256'] or '0' * 64)
        lines.extend([
            '    {',
            '        %s,' % json.dumps(profile['id']),
            '        %s,' % json.dumps(profile['label'], ensure_ascii=False),
            '        { %s },' % c_bytes(bytes.fromhex(profile['sha256'])),
            '        0x%xu, %du, 0x%xu, 0x%xu,' % (profile['targetRva'], profile['targetSize'], profile['vt1Rva'], profile['vt2Rva']),
            '        { %s },' % c_bytes(profile['prologue']),
            '        { %s },' % c_bytes(function_sha),
            '    },',
        ])
    lines.extend([
        '};',
        '',
        '#define NSP_AUDIODG_BUILD_COUNT (sizeof(nsp_audiodg_builds) / sizeof(nsp_audiodg_builds[0]))',
        '',
        'static inline const NspAudiodgBuild *nsp_audiodg_match(const unsigned char digest[32]) {',
        '    size_t index;',
        '    for (index = 0; index < NSP_AUDIODG_BUILD_COUNT; index++)',
        '        if (!memcmp(nsp_audiodg_builds[index].sha256, digest, 32)) return &nsp_audiodg_builds[index];',
        '    return NULL;',
        '}',
        '',
        'static inline void nsp_audiodg_hex(const unsigned char digest[32], char out[65]) {',
        '    static const char digits[] = "0123456789abcdef";',
        '    int index;',
        '    for (index = 0; index < 32; index++) {',
        '        out[index * 2] = digits[digest[index] >> 4];',
        '        out[index * 2 + 1] = digits[digest[index] & 15];',
        '    }',
        '    out[64] = 0;',
        '}',
        '',
        'static inline const char *nsp_audiodg_describe_supported(char *buffer, size_t capacity) {',
        '    size_t used = 0, index;',
        '    char hex[65];',
        '    if (capacity) buffer[0] = 0;',
        '    for (index = 0; index < NSP_AUDIODG_BUILD_COUNT && used < capacity; index++) {',
        '        int written;',
        '        nsp_audiodg_hex(nsp_audiodg_builds[index].sha256, hex);',
        '        written = snprintf(buffer + used, capacity - used, "%s%s (%s)", index ? "; " : "", hex, nsp_audiodg_builds[index].label);',
        '        if (written < 0 || (size_t)written >= capacity - used) break;',
        '        used += (size_t)written;',
        '    }',
        '    return buffer;',
        '}',
        '',
        'static inline const char *nsp_audiodg_unsupported_message(const unsigned char digest[32], char *buffer, size_t capacity) {',
        '    char hex[65];',
        '    char supported[1024];',
        '    nsp_audiodg_hex(digest, hex);',
        '    nsp_audiodg_describe_supported(supported, sizeof(supported));',
        '    snprintf(buffer, capacity, "Unsupported audiodg build: sha256=%s; supported: %s; add the verified build to contracts/audiodg-builds.json", hex, supported);',
        '    return buffer;',
        '}',
        '',
        'static inline int nsp_audiodg_prologue_ok(const void *address, const unsigned char expected[16]) {',
        '    return address != NULL && !memcmp(address, expected, 16);',
        '}',
        '',
        'static inline int nsp_audiodg_config_matches(const NspAudiodgBuild *profile, const unsigned char digest[32],',
        '        uint32_t target_rva, uint32_t target_size, uint32_t vt1_rva, uint32_t vt2_rva, const unsigned char prologue[16]) {',
        '    return profile != NULL && !memcmp(profile->sha256, digest, 32) && profile->target_rva == target_rva &&',
        '        profile->target_size == target_size && profile->vt1_rva == vt1_rva && profile->vt2_rva == vt2_rva &&',
        '        !memcmp(profile->prologue, prologue, 16);',
        '}',
        '',
        '#endif',
        '',
    ])
    return '\n'.join(lines)


def render_all(profiles):
    return {
        'tools/backend/audiodg_builds.py': render_python(profiles),
        'tools/zig-scheduler/audiodg_builds.zig': render_zig(profiles),
        'modules/zig-scheduler/audiodg_builds.zig': render_zig(profiles),
        'tools/endpoint-probe/Audiodg-Builds.h': render_header(profiles),
        'modules/native-capture/Audiodg-Builds.h': render_header(profiles),
    }


def main(argv):
    check = '--check' in argv[1:]
    unknown = [arg for arg in argv[1:] if arg != '--check']
    if unknown:
        fail('unknown arguments: ' + ' '.join(unknown))
    profiles = load_profiles()
    outputs = render_all(profiles)
    stale = []
    for relative in OUTPUTS:
        path = ROOT / relative
        text = outputs[relative]
        if check:
            current = path.read_text(encoding='utf-8') if path.is_file() else None
            if current is None or current.replace('\r\n', '\n') != text:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')
    if check:
        if stale:
            fail('stale generated files (run without --check): ' + ', '.join(stale))
        print('audiodg build tables are current (%d profiles)' % len(profiles))
        return 0
    print('Generated audiodg build tables (%d profiles): %s' % (len(profiles), ', '.join(profile['id'] for profile in profiles)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
